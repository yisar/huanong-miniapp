  onUnload() {
    this.stopLocationUpdates();
  },

  startLocationUpdates() {
    // 先获取一次当前位置
    this.getLocation();

    // 设置定时器定期获取位置
    const timer = setInterval(() => {
      this.getLocation();
    }, 3000);

    this.setData({
      locationTimer: timer
    });
  },

  stopLocationUpdates() {
    // 清除定时器
    if (this.data.locationTimer) {
      clearInterval(this.data.locationTimer);
      this.setData({
        locationTimer: null
      });
    }
  },

  getLocation() {
    my.getLocation({
      type: 'gcj02', // 坐标类型
      success: (res) => {
        console.log("获取位置成功", res);
        const {
          longitude,
          latitude
        } = res;

        // 更新地图位置和标记
        this.setData({
          longitude,
          latitude
        });


        // 定期上传位置
        // this.checkAndUploadLocation(res);
      },
      fail: (err) => {
        console.log("获取位置失败", err);
        my.showToast({
          content: '定位失败，请检查定位权限',
          type: 'fail'
        });
      }
    });
  },

